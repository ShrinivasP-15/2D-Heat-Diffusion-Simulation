"""### 4B. Check the FDM against an analytical solution

This test uses a known mathematical solution with a sine-shaped initial temperature field and zero-temperature boundaries. It checks how the numerical error changes as the grid is refined. The expected convergence is approximately second order.

"""

import numpy as np
def fdm_error(N,tend=0.05,r=0.2):
    x=np.linspace(0,1,N); X,Y=np.meshgrid(x,x,indexing='ij'); T=np.sin(np.pi*X)*np.sin(np.pi*Y)
    dx=1/(N-1); dt=r*dx*dx; steps=int(round(tend/dt))
    for _ in range(steps):
        Tn=T.copy(); Tn[1:-1,1:-1]=T[1:-1,1:-1]+r*(T[2:,1:-1]+T[:-2,1:-1]+T[1:-1,2:]+T[1:-1,:-2]-4*T[1:-1,1:-1]); T=Tn
    return np.abs(T-np.sin(np.pi*X)*np.sin(np.pi*Y)*np.exp(-2*np.pi**2*steps*dt)).max()
